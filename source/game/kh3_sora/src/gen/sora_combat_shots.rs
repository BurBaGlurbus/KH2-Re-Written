// The row type of the reference's sheet sora-combat-shots; rows come from the player's files at run time (crate::sheets).

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ShotShapeRow {
    pub id: &'static str,
    pub shot: &'static str,
    pub class_name: &'static str,
    pub group: &'static str,
    pub row: &'static str,
    pub shape: &'static str,
    pub mesh: &'static str,
    pub life: f32,
    pub no_destroy: bool,
    pub size: &'static [f32],
    pub inc_size: &'static [f32],
    pub max_size: &'static [f32],
    pub size_curve: &'static [f32],
    pub loc: &'static [f32],
    pub scale: &'static [f32],
    pub inc_scale: &'static [f32],
    pub max_scale: &'static [f32],
    pub interval: f32,
    pub map_hit: &'static str,
    pub particle: &'static str,
    pub particle_loc: &'static [f32],
    pub hit_effect: &'static str,
    pub hit_se: &'static str,
    pub hit_offset: f32,
    pub fire_effect: &'static str,
    pub fire_se: &'static str,
    pub spawn: &'static str,
}

pub static SHOT_SHAPES: std::sync::LazyLock<Vec<ShotShapeRow>> = std::sync::LazyLock::new(|| {
    crate::sheets::Table::named("sora-combat-shots").rows().map(|r| ShotShapeRow {
        id: r.text("id"),
        shot: r.text("shot"),
        class_name: r.text("class"),
        group: r.text("group"),
        row: r.text("row"),
        shape: r.text("shape"),
        mesh: r.text("mesh"),
        life: r.num("life"),
        no_destroy: r.yesno("no_destroy"),
        size: r.nums("size"),
        inc_size: r.nums("inc_size"),
        max_size: r.nums("max_size"),
        size_curve: r.nums("size_curve"),
        loc: r.nums("loc"),
        scale: r.nums("scale"),
        inc_scale: r.nums("inc_scale"),
        max_scale: r.nums("max_scale"),
        interval: r.num("interval"),
        map_hit: r.text("map_hit"),
        particle: r.text("particle"),
        particle_loc: r.nums("particle_loc"),
        hit_effect: r.text("hit_effect"),
        hit_se: r.text("hit_se"),
        hit_offset: r.num("hit_offset"),
        fire_effect: r.text("fire_effect"),
        fire_se: r.text("fire_se"),
        spawn: r.text("spawn"),
    }).collect()
});
